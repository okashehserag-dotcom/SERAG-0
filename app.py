def print_section(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


def print_bullets(items):
    for item in items:
        print(f"- {item}")


def show_unit_summary(data):
    print_section(unit_title)

    print("الفكرة العامة:")
    print(data["الفكرة_العامة"]["ملخص"])
    print("\nالشرح:")
    print(data["الفكرة_العامة"]["شرح"])
    print("\nنقاط سريعة:")
    print_bullets(data["الفكرة_العامة"]["نقاط"])

    for key in ["الدرس_الأول", "الدرس_الثاني", "الدرس_الثالث"]:
        lesson = data[key]
        print_section(lesson["العنوان"])
        print("الملخص:")
        print(lesson["ملخص"])
        print("\nالشرح:")
        print(lesson["شرح"])
        print("\nتحويل الدرس إلى نقاط:")
        print_bullets(lesson["نقاط"])

    print_section("مراجعة الوحدة")
    print("الملخص:")
    print(data["مراجعة_الوحدة"]["ملخص"])
    print("\nالشرح:")
    print(data["مراجعة_الوحدة"]["شرح"])
    print("\nنقاط المراجعة:")
    print_bullets(data["مراجعة_الوحدة"]["نقاط"])


